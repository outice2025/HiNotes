package com.hiapps.hinotes.ui.theme

import androidx.compose.material3.ColorScheme
import androidx.compose.ui.graphics.Color
import java.io.File
import kotlin.math.pow

/**
 * Standalone checks for [nearestPairTo] and for the colours a home-screen widget is painted with,
 * run on a desktop JVM by tools/verify/run.ps1.
 *
 * The home screen paints its delete action in whichever pair of roles in the active scheme is
 * nearest the destructive red the button was specified with. That is arithmetic standing in for a
 * designer's eye, so it is executed here rather than assumed: every light scheme the app ships has
 * to answer with its own error pair, because a scheme that answered with its primary would paint
 * the delete button in the accent colour - the one thing a destructive action must not be.
 *
 * The widget's card is filled with the scheme's `onSecondary` and its text drawn in `onSurface` and
 * `onSurfaceVariant` (see WidgetStyle.kt), so the two text roles are measured against that fill
 * here. A palette is generated rather than hand-checked, and a body that came out too faint on the
 * fill would otherwise only be seen on a home screen. The measurement runs for every scheme the app
 * ships, in both modes, and the AMOLED treatment is checked to leave the card's colours untouched.
 *
 * The list below is also what keeps the check complete: the declarations are counted in the sources
 * as well, so a palette added there without being added here fails the check instead of quietly
 * going unverified.
 */
object ThemeChecks {

    private var failures = 0

    private fun check(name: String, condition: Boolean, detail: String = "") {
        if (condition) {
            println("  ok    $name")
        } else {
            failures++
            println("  FAIL  $name ${if (detail.isEmpty()) "" else "-> $detail"}")
        }
    }

    @JvmStatic
    fun main(args: Array<String>) {
        println("nearest button colour, per shipped light scheme")

        val light = listOf(
            "BlueLight" to BlueLight,
            "TeaGreenLight" to TeaGreenLight,
            "LightGrayLight" to LightGrayLight,
            "RedLight" to RedLight,
            "LightPurpleLightColorScheme" to LightPurpleLightColorScheme,
            "OrangeLight" to OrangeLight,
            "YellowLight" to YellowLight,
        )
        val dark = listOf(
            "BlueDark" to BlueDark,
            "TeaGreenDark" to TeaGreenDark,
            "LightGrayDark" to LightGrayDark,
            "RedDark" to RedDark,
            "LightPurpleDarkColorScheme" to LightPurpleDarkColorScheme,
            "OrangeDark" to OrangeDark,
            "YellowDark" to YellowDark,
        )

        val reference = ColorTokens.DestructiveReference
        light.forEach { (name, scheme) ->
            val pair = scheme.nearestPairTo(reference)
            val expected = ColorPair(scheme.error, scheme.onError)
            check(
                "$name answers with its own red",
                pair == expected,
                "got ${pair.container} / ${pair.content}, expected ${expected.container}",
            )
        }

        // The design palette's error role is the colour the button was specified from, which is why
        // the answer above is the one the design asked for.
        check(
            "the reference is the design palette's error",
            reference == ColorTokens.Light.Error,
            reference.toString(),
        )

        val declared = declaredSchemes("light")
        check(
            "every light scheme in the sources is checked here",
            declared == light.map { it.first }.toSet(),
            "sources declare $declared",
        )

        widgetCard(light, dark)

        report()
    }

    /**
     * The colours a card draws its text in, measured against the fill it is drawn on.
     *
     * A card's fill is `onSecondary` and its title and body are the scheme's `onSurface` and
     * `onSurfaceVariant` (see WidgetStyle.kt), so the two text roles are measured with the WCAG
     * contrast ratio below - the same question a reader's eye asks of the card. The dark schemes are
     * measured after `liftDarkSurfaces`, exactly as the widget applies them, and the AMOLED
     * flattening is asserted to leave the fill and both text roles where they were, so one
     * measurement covers a card with AMOLED dark switched on and off.
     *
     * A wallpaper-derived scheme cannot be built here - the platform builds it from the device's
     * wallpaper - but it is generated by the same tonal-palette rules: `onSecondary` is tone 100 in
     * a light scheme and tone 20 in a dark one, and the text roles are tones 10/30 and 90/80. The
     * shipped schemes are generated exactly that way, so measuring them measures that contract.
     */
    private fun widgetCard(
        light: List<Pair<String, ColorScheme>>,
        dark: List<Pair<String, ColorScheme>>,
    ) {
        println("widget card text on its onSecondary fill, per shipped scheme")

        light.forEach { (name, scheme) ->
            checkCardText(name, scheme)
        }
        dark.forEach { (name, scheme) ->
            // A dark card is painted from the ramp the app lifts, not the one the palette declares.
            checkCardText(name, scheme.liftDarkSurfaces())
        }

        val declaredDark = declaredSchemes("dark")
        check(
            "every dark scheme in the sources is checked here",
            declaredDark == dark.map { it.first }.toSet(),
            "sources declare $declaredDark",
        )

        // The flattening is required to move only the surface roles. If it ever repainted the fill
        // or the text, the ratios measured above would no longer describe a card on such a panel,
        // and this is where that would fail instead of on a phone.
        val moved = dark.filterNot { (_, scheme) ->
            val lifted = scheme.liftDarkSurfaces()
            val oled = lifted.toOled()
            oled.onSecondary == lifted.onSecondary &&
                oled.onSurface == lifted.onSurface &&
                oled.onSurfaceVariant == lifted.onSurfaceVariant
        }.map { it.first }
        check(
            "AMOLED dark leaves the card's fill and text roles alone",
            moved.isEmpty(),
            "moved by $moved",
        )

        val card = File("app/src/main/java/com/hiapps/hinotes/widget/WidgetStyle.kt")
        val cardSource = if (card.isFile) card.readText() else ""
        check(
            "the card's fill is the scheme's onSecondary, with no dial matching left",
            cardSource.contains("container = scheme.onSecondary.toArgb()") &&
                !cardSource.contains("widgetSurface"),
            "read from $card",
        )
    }

    /** [check] that both of [scheme]'s card text roles clear [MIN_TEXT_CONTRAST] on its fill. */
    private fun checkCardText(name: String, scheme: ColorScheme) {
        val fill = scheme.onSecondary
        val title = contrastRatio(scheme.onSurface, fill)
        val body = contrastRatio(scheme.onSurfaceVariant, fill)
        check(
            "$name's card text is legible on its onSecondary fill",
            title >= MIN_TEXT_CONTRAST && body >= MIN_TEXT_CONTRAST,
            "title $title:1, body $body:1, least accepted $MIN_TEXT_CONTRAST:1",
        )
    }

    /** The WCAG relative-luminance contrast between two sRGB colours, as a ratio from 1 to 21. */
    private fun contrastRatio(a: Color, b: Color): Float {
        val luminanceA = a.relativeLuminance()
        val luminanceB = b.relativeLuminance()
        return (maxOf(luminanceA, luminanceB) + 0.05f) / (minOf(luminanceA, luminanceB) + 0.05f)
    }

    /** One colour channel's linear-light value, as WCAG defines it for sRGB. */
    private fun linear(channel: Float): Float =
        if (channel <= 0.03928f) channel / 12.92f else ((channel + 0.055f) / 1.055f).pow(2.4f)

    /** The relative luminance WCAG builds its contrast ratio from. */
    private fun Color.relativeLuminance(): Float =
        0.2126f * linear(red) + 0.7152f * linear(green) + 0.0722f * linear(blue)

    /** The least contrast a card's title or body must clear; WCAG AA for normal-sized text. */
    private const val MIN_TEXT_CONTRAST = 4.5f

    /** The schemes the palette sources declare for one mode, read as text. */
    private fun declaredSchemes(kind: String): Set<String> {
        val files = listOf("AccentPalettes.kt", "ColorSchemes.kt")
            .map { File("app/src/main/java/com/hiapps/hinotes/ui/theme/$it") }
        return files.filter { it.isFile }
            .flatMap { file ->
                SCHEME_DECLARATION.findAll(file.readText())
                    .filter { it.groupValues[2] == kind }
                    .map { it.groupValues[1] }
            }
            .toSet()
    }

    /** `val Name: ColorScheme = lightColorScheme(` and its dark counterpart. */
    private val SCHEME_DECLARATION = Regex("val (\\w+): ColorScheme = (\\w+)ColorScheme\\(")

    private fun report() {
        if (failures == 0) {
            println("theme checks: all checks passed")
        } else {
            println("theme checks: $failures check(s) FAILED")
            throw IllegalStateException("$failures theme check(s) failed")
        }
    }
}
